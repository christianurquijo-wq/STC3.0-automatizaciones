SELECT 
U._ID AS USER_ID,
U.INCREMENTAL_USER_CODE AS ID_SIS,
U.PROFILE_FULL_NAME,
U.PROFILE_DOC_NUMBER,
CASE
  WHEN A.ATTENDANCE_STATUS = 'todas-las-sesiones_asistio' THEN 100
  WHEN A.ATTENDANCE_STATUS IS NULL THEN 0
  ELSE 0
END AS ATTENDANCE_STATUS,
CS.START_DATE AS FECHA_ASISTENCIA,
A.__CLASSSESSION,
CS.NUMBER_SESSION


FROM `potent-poetry-284019.DSS3_SIS.ES3100010_user` U
LEFT JOIN `potent-poetry-284019.DSS3_SIS.ES3100411_participants` A
  ON A.USER = U._ID 
LEFT JOIN `potent-poetry-284019.DSS3_SIS.ES3100410_class_session` CS
  ON A.__CLASSSESSION = CS._ID
