SELECT
  E100010._ID AS USER_ID,
  E100010.INCREMENTAL_USER_CODE AS ID_SIS,
  concat(E100010.PROFILE_FIRST_NAME , " " , E100010.PROFILE_LAST_NAME) AS NOMBRE,
  E100100_PR.NAME AS Paquete,
  E100415.NAME AS PROGRAMA,
  E100100_SE.NAME AS CARRIL,
  ROUND(E100201.COMPLETED_STATUS, 3) AS PROGRESO,
  E100201.COMPLETED_DATE AS FECHA_FINALIZACION_ASINCRONICA,
  COALESCE(E100201.LESSONS_COMPLETED, "0") LECCIONES_COMPLETADAS,

  ---- Id's
  
  --E100201.__INDEX statistic_index,
  --E100100_PR._ID AS program_id,
  E100200.STRUCTURE AS GROUP_ID,
  E100201.ACADEMIC_COMPONENT AS PROGRAM_ID,
  --E100150.ACADEMIC_COMPONENT_CATEGORY acamedic_component_category_id,
  --E100100_GR.CONFIG_SUBJECT subject_id
-- DSS3_SIS.ES3 DSS3_SIS.ES3
FROM `potent-poetry-284019.DSS3_SIS.ES3100010_user` E100010
LEFT JOIN `potent-poetry-284019.DSS3_SIS.ES3100200_user_statistic` E100200
  ON E100010._ID = E100200.USER
LEFT JOIN `potent-poetry-284019.DSS3_SIS.ES3100100_structure` E100100_GR
  ON E100200.STRUCTURE  = E100100_GR._ID
LEFT JOIN `potent-poetry-284019.DSS3_SIS.ES3100100_structure` E100100_SE
  ON E100100_GR.PARENT = E100100_SE._ID
LEFT JOIN `potent-poetry-284019.DSS3_SIS.ES3100100_structure` AS E100100_PE
  ON E100100_PE._ID = E100100_SE.PARENT
LEFT JOIN `potent-poetry-284019.DSS3_SIS.ES3100100_structure` AS E100100_PR
  ON E100100_PR._ID = E100100_PE.PARENT
LEFT JOIN `potent-poetry-284019.DSS3_SIS.ES3100201_statistics` E100201
  ON E100201.__MODEL = E100200._ID
LEFT JOIN `potent-poetry-284019.DSS3_SIS.ES3100150_academic_component` E100150
  ON E100201.ACADEMIC_COMPONENT = E100150._ID
LEFT JOIN `potent-poetry-284019.DSGE_SIS.EGE100812_academic_component_category` E100812
  ON E100150.ACADEMIC_COMPONENT_CATEGORY = E100812._ID
LEFT JOIN `potent-poetry-284019.DSS3_SIS.ES3100415_subject` E100415
   ON E100415._ID = E100100_GR.CONFIG_SUBJECT

WHERE
E100010.DELETED IS NOT TRUE
AND NOT REGEXP_CONTAINS(E100100_PR.NAME, 'Básico')
-- AND
-- E100200.DELETED IS NOT TRUE AND
AND E100150.ACADEMIC_COMPONENT_CATEGORY in ('5fc1416f18d8cca721c0b9e0') -- Escoge los academic_componet tipo curso
--AND E100010.INCREMENTAL_USER_CODE = 458
ORDER BY E100010.INCREMENTAL_USER_CODE DESC
