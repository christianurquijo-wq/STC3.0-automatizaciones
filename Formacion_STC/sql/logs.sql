SELECT 
U._ID AS USER_ID,
U.INCREMENTAL_USER_CODE AS ID_SIS,
D.INCREMENTAL_CONTACT_CODE AS ID_CRM,
U.PROFILE_FULL_NAME AS NOMBRE_USUARIOS,
U.PROFILE_DOC_NUMBER AS DOCUMENTO,
AC.NAME AS LECCION,
LR.ACADEMIC_COMPONENT AS LECCION_ID,
LVAC.CREATED_AT AS FECHA_LOG, 
ACC.DESCRIPTION AS TIPO,
COALESCE(ROUND(LR.COMPLETED_STATUS, 3), 0) AS PROGRESO_LECCION,
COALESCE(ROUND((LR.TIME_VIEW/3600), 3), 0) AS TIME_VIEW_LECCION,

S_P.NAME AS PROGRAMA, 
PLVAC.CREATED_AT AS FECHA_LOG_PROGRAMA, 
PLR.ACADEMIC_COMPONENT AS PROGRAMA_ID,
LPACC.DESCRIPTION AS PARENT_CATEGORY,
COALESCE(ROUND(PLR.COMPLETED_STATUS, 3), 0) AS PROGRESO_PROGRAMA,
COALESCE(ROUND((PLR.TIME_VIEW/3600), 3), 0) AS TIME_VIEW_PROGRAMA

FROM `potent-poetry-284019.DSS3_SIS.ES3100010_user` U
LEFT JOIN `potent-poetry-284019.DSS3_SIS.ES3101000_log_view_academic_component` LVAC
  ON LVAC.USER = U._ID
LEFT JOIN `potent-poetry-284019.DSS3_SIS.ES3101001_logs` LR
  ON LR.__MODEL = LVAC._ID
LEFT JOIN `potent-poetry-284019.DSS3_SIS.ES3100150_academic_component` AC
  ON LR.ACADEMIC_COMPONENT = AC._ID
INNER JOIN 
        (SELECT * FROM `potent-poetry-284019.DSGE_SIS.EGE100812_academic_component_category` 
        WHERE _ID = '5fc1416f18d8cca721c0b9e2')  ACC
  ON AC.ACADEMIC_COMPONENT_CATEGORY = ACC._ID
LEFT JOIN `potent-poetry-284019.DSS3_SIS.ES3100150_academic_component` F_P
  ON F_P._ID = AC.PARENT
LEFT JOIN `potent-poetry-284019.DSS3_SIS.ES3100150_academic_component` S_P
  ON F_P.PARENT = S_P._ID
LEFT JOIN `potent-poetry-284019.DSGE_SIS.EGE100812_academic_component_category` SPACC
  ON S_P.ACADEMIC_COMPONENT_CATEGORY = SPACC._ID
LEFT JOIN `potent-poetry-284019.DSS3_SIS.ES3100150_academic_component` L_P
  ON S_P.PARENT = L_P._ID
LEFT JOIN `potent-poetry-284019.DSGE_SIS.EGE100812_academic_component_category` LPACC
  ON S_P.ACADEMIC_COMPONENT_CATEGORY = LPACC._ID

LEFT JOIN `potent-poetry-284019.DSS3_SIS.ES3101000_log_view_academic_component` PLVAC
  ON U._ID = PLVAC.USER
  AND LVAC.CREATED_AT = PLVAC.CREATED_AT
LEFT JOIN `potent-poetry-284019.DSS3_SIS.ES3101001_logs` PLR
  ON PLR.__MODEL = PLVAC._ID
  AND PLR.ACADEMIC_COMPONENT = S_P._ID
LEFT JOIN `potent-poetry-284019.DSS3_CRM.ES3200020_enrollment` D
  ON U._ID = D.USER_SIS

--QUALIFY ROW_NUMBER() OVER(PARTITION BY U._ID, PLR.ACADEMIC_COMPONENT ORDER BY  PLVAC.CREATED_AT DESC) = 1 
ORDER BY PLVAC.CREATED_AT DESC
